import { expect, test } from "@playwright/test"

test("dependency browsing stays virtualized, searchable and keyboard accessible", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/catalog/100?rows=256")
  await expect(page.getByRole("heading", { name: "Midnight aviator", exact: true })).toBeVisible()
  await expect(page.getByRole("tab", { name: "Dependencies", exact: true })).toBeVisible()
  // Opening an item does not fetch the model until Dependencies is opened.
  expect(await page.evaluate(() => window.__bonsaiPerf.calls.itemDependencies ?? 0)).toBe(0)
  await page.getByRole("tab", { name: "Dependencies", exact: true }).click()
  await expect(page.getByText("256 of 256 assets")).toBeVisible()
  await expect(page.getByRole("table", { name: "Item dependencies" })).toBeVisible()
  expect(await page.getByRole("table", { name: "Item dependencies" }).getByRole("row").count()).toBeLessThan(35)
  const search = page.getByRole("textbox", { name: "Search dependencies" })
  await search.fill("aviator mesh")
  await expect(page.getByText("1 of 256 assets")).toBeVisible()
  await page.getByRole("button", { name: "Mesh", exact: true }).focus()
  await page.keyboard.press("Enter")
  const dialog = page.getByRole("dialog", { name: "References to Aviator mesh" })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText("Midnight aviator/Handle")).toBeVisible()
  await page.keyboard.press("Escape")
  await search.fill("1000102")
  await expect(page.getByText("Details unavailable", { exact: true })).toBeVisible()
  await search.fill("does not exist")
  await expect(page.getByText("No matching dependencies")).toBeVisible()
  await search.fill("")
  await expect(page.getByText("256 of 256 assets")).toBeVisible()
  await page.setViewportSize({ width: 720, height: 900 })
  const actions = page.getByRole("button", { name: "Actions for Aviator mesh", exact: true })
  await actions.scrollIntoViewIfNeeded()
  await expect(actions).toBeInViewport()
  expect(errors).toEqual([])
})
