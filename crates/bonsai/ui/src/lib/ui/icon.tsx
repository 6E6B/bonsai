export type IconName = keyof typeof svgs

/** The filled variant of an icon when one exists, else the icon itself. */
export function filledIcon(name: IconName): IconName {
  const fill = `${name}-fill`
  return fill in svgs ? (fill as IconName) : name
}

/** The SVG's children, without its outer `<svg>` tag. Every Phosphor icon is a 256×256 box. */
const inner = Object.fromEntries(
  Object.entries(svgs).map(([name, svg]) => [name, svg.replace(/^<svg[^>]*>|<\/svg>\s*$/g, "")]),
) as Record<IconName, string>

export interface IconProps extends ComponentProps<"svg"> {
  name: IconName
  size?: number
}

export function Icon(props: IconProps) {
  const [local, rest] = splitProps(props, ["name", "size"])
  return (
    <svg
      data-component="icon"
      data-icon={local.name}
      width={local.size ?? 16}
      height={local.size ?? 16}
      viewBox="0 0 256 256"
      fill="currentColor"
      aria-hidden="true"
      innerHTML={inner[local.name]}
      {...rest}
    />
  )
}
