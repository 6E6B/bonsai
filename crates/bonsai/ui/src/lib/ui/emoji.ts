/** Groups to show for a search: every group for a blank query, otherwise one "Results" group
 * with the emoji whose words start with, or contain, each word typed. */
export function searchEmoji(query: string, groups: readonly EmojiGroup[] = EMOJI_GROUPS): EmojiGroup[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean)
  if (words.length === 0) return [...groups]
  const hits = groups
    .flatMap((g) => g.emoji)
    .filter(([, text]) => words.every((w) => text.split(" ").some((t) => t.includes(w))))
  return hits.length > 0 ? [{ id: "results", label: "Results", emoji: hits }] : []
}
