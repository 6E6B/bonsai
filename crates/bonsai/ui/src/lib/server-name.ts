/** FNV-1a over the UTF-16 code units, then a murmur3 finalizer so nearby ids spread out. */
function hash(text: string) {
  let h = 0x811c9dc5
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  h ^= h >>> 16
  h = Math.imul(h, 0x85ebca6b)
  h ^= h >>> 13
  h = Math.imul(h, 0xc2b2ae35)
  h ^= h >>> 16
  return h >>> 0
}

/** The name for a server, like "Amber Otter". Job ids are compared ignoring case and spaces. */
export function serverName(jobId: string) {
  const h = hash(jobId.trim().toLowerCase())
  return `${ADJECTIVES[h % ADJECTIVES.length]} ${NOUNS[Math.floor(h / ADJECTIVES.length) % NOUNS.length]}`
}

export const serverNameWords = { adjectives: ADJECTIVES, nouns: NOUNS }
